"""Шаг 1. Одно число, которое говорит, насколько модель ошибается.

Данные: 60 сделок по квартирам в файле data/apartments.csv.
Модель: цена = w1*площадь + w2*минут_до_метро + w3*этаж + b.
Здесь мы ничего не обучаем. Мы берём три набора чисел, придуманных наугад,
и смотрим, какой из них ошибается меньше.

Запуск:  ./.venv/bin/python ch02/01_loss.py
"""

import csv
from pathlib import Path

import numpy as np

# читаем таблицу: первые три колонки это признаки, последняя, правильный ответ
rows = list(csv.DictReader((Path(__file__).parent / "data/apartments.csv").open(encoding="utf-8")))
X = np.array([[float(r["area"]), float(r["metro_min"]), float(r["floor"])] for r in rows])
y = np.array([float(r["price"]) for r in rows])

print(f"квартир в таблице: {len(y)}")
print(f"площадь: от {X[:, 0].min():.0f} до {X[:, 0].max():.0f} метров")
print(f"цена: от {y.min() / 1e6:.2f} до {y.max() / 1e6:.2f} миллиона рублей\n")


def predict(X, w, b):
    """Предсказание модели: сумма признаков с весами плюс свободный член."""
    return X @ w + b


def mse(y_true, y_pred):
    """Среднеквадратичная ошибка: средний квадрат промаха."""
    return float(np.mean((y_true - y_pred) ** 2))


# три набора весов наугад: первый вообще мимо, третий ближе к правде
candidates = {
    "все веса по нулям": (np.array([0.0, 0.0, 0.0]), 0.0),
    "цена только от площади": (np.array([100_000.0, 0.0, 0.0]), 0.0),
    "площадь, метро, этаж": (np.array([130_000.0, -60_000.0, 40_000.0]), 0.0),
}

for name, (w, b) in candidates.items():
    err = mse(y, predict(X, w, b))
    # корень из ошибки возвращает нас в рубли, так понятнее
    print(f"{name:26} ошибка {err:.3e}   в рублях примерно {err ** 0.5 / 1e6:.2f} млн")

print("\nЧем меньше число, тем лучше подобраны веса. Ни один набор мы не обучали,")
print("все три придуманы руками. Обучение начинается в файле 02_train.py.")

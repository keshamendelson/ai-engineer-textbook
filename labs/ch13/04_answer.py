"""Шаг 4. Ответ модели по найденным кускам, со ссылкой на источник.

Здесь собирается то, ради чего всё затевалось. Находим три куска, складываем их
в один текст с номерами, просим модель ответить только по этому тексту и назвать
номера, на которые она опиралась. Если ответа в кусках нет, модель обязана
сказать, что не знает.

Перед запуском нужны три переменные окружения, см. labs/README.md.

Запуск:  ./.venv/bin/python ch13/04_answer.py
         ./.venv/bin/python ch13/04_answer.py "свой вопрос"
"""

import sys

from common import ask_model, chunks, search

SYSTEM = """Ты отвечаешь на вопросы сотрудников по внутренним документам компании.
Правила: отвечай только тем, что есть в приведённых фрагментах. Если ответа в них
нет, так и скажи. В конце ответа перечисли номера фрагментов, на которые опирался.
Отвечай по-русски, коротко, без вступлений."""

question = sys.argv[1] if len(sys.argv) > 1 else "когда выплатят компенсацию за неиспользованный отпуск"

found = search(question, k=3)
context = "\n\n".join(
    f"[{n}] {chunks[i]['doc']}. {chunks[i]['section']}\n{chunks[i]['text']}"
    for n, i in enumerate(found, 1))

print(f"Вопрос: {question}\n")
print("Найденные куски, которые уходят модели:")
for n, i in enumerate(found, 1):
    print(f"  [{n}] {chunks[i]['file']} · {chunks[i]['section']}")
print()

answer, usage = ask_model(SYSTEM, f"Фрагменты документов:\n\n{context}\n\nВопрос: {question}")

print("Ответ модели:")
print(answer)
print()
if usage:
    print(f"Токенов потрачено: вход {usage.get('prompt_tokens', '?')}, "
          f"выход {usage.get('completion_tokens', '?')}")
print("\nПроверьте ответ по исходным документам в папке data. Модель не должна была")
print("добавить ни одного факта, которого нет в кусках выше. Если добавила, это")
print("выдумка, и лечится она не текстом запроса, а проверкой ответа, глава 15.")
